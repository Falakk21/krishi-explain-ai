import io
import os
from pathlib import Path
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

from app.schemas.models import AssessmentResponse
from app.core.config import settings

def generate_assessment_pdf(assessment: AssessmentResponse) -> bytes:
    """
    Generates a PDF report for a KrishiExplain AI assessment.
    Returns bytes of the generated PDF document.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    # Brand Colors: Forest Green (#174D38), Sage (#A8C3A0), Charcoal (#26332C), Pale Mint (#E8F1E8)
    c_forest = colors.HexColor("#174D38")
    c_deep = colors.HexColor("#103C2C")
    c_sage = colors.HexColor("#A8C3A0")
    c_palemint = colors.HexColor("#E8F1E8")
    c_charcoal = colors.HexColor("#26332C")
    c_cream = colors.HexColor("#F8F7F0")
    c_gray = colors.HexColor("#78847B")
    c_amber = colors.HexColor("#D97706")
    c_red = colors.HexColor("#DC2626")
    c_green = colors.HexColor("#16A34A")

    # Custom Typography Styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=c_forest
    )

    tagline_style = ParagraphStyle(
        "DocTagline",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=10,
        leading=13,
        textColor=c_gray
    )

    h1_style = ParagraphStyle(
        "SectionH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=c_deep,
        spaceBefore=10,
        spaceAfter=4
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=c_charcoal
    )

    body_bold = ParagraphStyle(
        "BodyDarkBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=c_charcoal
    )

    badge_style = ParagraphStyle(
        "BadgeText",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white
    )

    story = []

    # Header Banner
    header_data = [
        [
            Paragraph("KrishiExplain AI", title_style),
            Paragraph(f"ASSESSMENT ID: <b>{assessment.assessment_id}</b><br/>Generated: {assessment.timestamp[:10]}", body_style)
        ],
        [
            Paragraph("Climate Insights. Stronger Harvests. Resilient Agriculture.", tagline_style),
            Paragraph(
                "<font color='#B45309'><b>[DEMONSTRATION RUN]</b></font>" if assessment.is_demo 
                else "<font color='#16A34A'><b>[VALIDATED MODEL RUN]</b></font>",
                body_style
            )
        ]
    ]
    header_table = Table(header_data, colWidths=[4.2 * inch, 3.0 * inch])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1.5, color=c_forest, spaceBefore=2, spaceAfter=8))

    # Demo Banner if Demo Mode
    if assessment.is_demo:
        demo_banner = Table(
            [[Paragraph("<b>DEMONSTRATION REPORT</b>: Values in this report are simulated for evaluation and were not generated by a live predictive production model.", body_style)]],
            colWidths=[7.2 * inch]
        )
        demo_banner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor("#92400E")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#F59E0B")),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('LEFTPADDING', (0, 0), (-1, -1), 8),
            ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ]))
        story.append(demo_banner)
        story.append(Spacer(1, 8))

    # 1. Executive Summary & Prediction
    story.append(Paragraph("1. Executive Summary & Impact Prediction", h1_style))
    p = assessment.prediction
    pred_summary_text = (
        f"<b>Target Crop:</b> {p.crop} &nbsp;&nbsp;|&nbsp;&nbsp; <b>Region:</b> {p.region}<br/>"
        f"<b>Predicted Rabi Yield:</b> <font color='#174D38' size='+2'><b>{p.predicted_yield:.2f} {p.yield_unit}</b></font> "
        f"({p.yield_change_pct:+.1f}% vs Regional Baseline of {p.baseline_yield:.2f} {p.yield_unit})"
    )
    summary_box = Table([[Paragraph(pred_summary_text, body_style)]], colWidths=[7.2 * inch])
    summary_box.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), c_palemint),
        ('BOX', (0, 0), (-1, -1), 1, c_sage),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(summary_box)
    story.append(Spacer(1, 10))

    # 2. Input Parameters
    story.append(Paragraph("2. Agro-Climatic Input Parameters", h1_style))
    inp = assessment.input_summary
    input_rows = [
        [Paragraph("<b>Parameter</b>", body_bold), Paragraph("<b>Value</b>", body_bold), Paragraph("<b>Unit</b>", body_bold), Paragraph("<b>Agronomic Baseline Range</b>", body_bold)],
        ["Average Rabi Temperature", f"{inp.avg_temperature:.1f}", "°C", "15.0 - 18.5 °C (Optimal tillering)"],
        ["Peak / Terminal Heat Temp", f"{inp.max_temperature:.1f}", "°C", "< 31.0 °C (Critical threshold)"],
        ["Cumulative Rabi Rainfall", f"{inp.rainfall_mm:.1f}", "mm", "75 - 140 mm (Rabi season total)"],
        ["Relative Humidity", f"{inp.humidity_pct:.1f}", "%", "45 - 65 % (Seasonal mean)"],
        ["Soil Moisture Index", f"{inp.soil_moisture_pct:.1f}", "%", "35 - 55 % (Root-zone capacity)"],
        ["Terminal Heat Days (>31°C)", f"{inp.heat_wave_days}", "days", "0 - 5 days during grain filling"],
        ["Irrigation Infrastructure", f"{inp.irrigation_type}", "category", "Assured Tubewell & Canal network"]
    ]
    input_table = Table(input_rows, colWidths=[2.2 * inch, 1.0 * inch, 0.8 * inch, 3.2 * inch])
    input_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), c_forest),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_cream]),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
    ]))
    story.append(input_table)
    story.append(Spacer(1, 10))

    # 3. Climate Factor Contributions
    story.append(Paragraph("3. Climate Factor Contributions", h1_style))
    story.append(Paragraph(f"<i>{assessment.plain_language_explanation}</i>", body_style))
    story.append(Spacer(1, 6))

    shap_rows = [
        [
            Paragraph("<b>Feature</b>", body_bold),
            Paragraph("<b>Observed</b>", body_bold),
            Paragraph("<b>Contribution</b>", body_bold),
            Paragraph("<b>Direction</b>", body_bold),
            Paragraph("<b>Plain-Language Interpretation</b>", body_bold)
        ]
    ]
    for c in assessment.key_contributors:
        color_tag = "#16A34A" if c.direction == "positive" else "#DC2626"
        dir_label = "Favorable (+)" if c.direction == "positive" else "Adverse (-)"
        observed_display = (
            f"{c.observed_value:.1f} {c.unit}"
            if isinstance(c.observed_value, (int, float))
            else str(c.observed_value)
        )
        shap_rows.append([
            c.feature_label,
            observed_display,
            f"<font color='{color_tag}'><b>{c.shap_value:+.2f} t/ha</b></font>",
            dir_label,
            Paragraph(c.interpretation, body_style)
        ])

    shap_table = Table(shap_rows, colWidths=[1.6 * inch, 0.9 * inch, 1.1 * inch, 0.9 * inch, 2.7 * inch])
    shap_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), c_forest),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_cream]),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('FONTSIZE', (0, 0), (-1, -1), 8),
    ]))
    story.append(shap_table)
    story.append(Spacer(1, 10))

    # 4. Risk Assessment
    story.append(Paragraph("4. Agro-Climatic Vulnerability & Risk Assessment", h1_style))
    risk_rows = [
        [Paragraph("<b>Risk Category</b>", body_bold), Paragraph("<b>Severity</b>", body_bold), Paragraph("<b>Score</b>", body_bold), Paragraph("<b>Assessment Findings</b>", body_bold)]
    ]
    for r in assessment.risk_assessment:
        badge_color = "#DC2626" if r.level in ["High", "Critical"] else ("#D97706" if r.level == "Moderate" else "#16A34A")
        risk_rows.append([
            r.category,
            f"<font color='{badge_color}'><b>{r.level}</b></font>",
            f"{r.score:.0f}/100",
            Paragraph(f"{r.description}<br/><font color='#6B7280' size='7'>{r.threshold_info}</font>", body_style)
        ])
    risk_table = Table(risk_rows, colWidths=[1.8 * inch, 0.9 * inch, 0.8 * inch, 3.7 * inch])
    risk_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), c_forest),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_cream]),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
    ]))
    story.append(risk_table)
    story.append(Spacer(1, 10))

    # 5. Evidence-Based Adaptation Insights
    story.append(Paragraph("5. Evidence-Based Agricultural Adaptation Strategies", h1_style))
    for strat in assessment.adaptation_insights:
        strat_text = (
            f"<b>{strat.strategy_title}</b> ({strat.risk_factor})<br/>"
            f"<b>Action:</b> {strat.action_summary}<br/>"
            f"<b>Agronomic Rationale:</b> {strat.why_relevant}<br/>"
            f"<b>Limitations & Constraints:</b> {strat.practical_limitations}<br/>"
            f"<i>Source: {strat.credible_source} [Rule-Based Guidance]</i>"
        )
        strat_box = Table([[Paragraph(strat_text, body_style)]], colWidths=[7.2 * inch])
        strat_box.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), c_cream),
            ('BOX', (0, 0), (-1, -1), 0.75, c_sage),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(strat_box)
        story.append(Spacer(1, 4))

    # 6. Provenance & Disclaimers
    story.append(Spacer(1, 6))
    story.append(Paragraph("6. Data Provenance & Scientific Disclaimers", h1_style))
    disclaimer_text = (
        "<b>Data Sources:</b> Directorate of Economics & Statistics (DES Agri), India Meteorological Department (IMD), "
        "NASA POWER Meteorological Dataset, FAOSTAT.<br/>"
        "<b>Scientific Disclaimer:</b> " + assessment.scientific_disclaimer + "<br/>"
        "<b>Estimate Notice:</b> Factor contributions describe patterns in the available records and should not be "
        "interpreted as proof of biological cause and effect. Estimates do not guarantee yield outcomes."
    )
    disclaimer_box = Table([[Paragraph(disclaimer_text, body_style)]], colWidths=[7.2 * inch])
    disclaimer_box.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F3F4F6")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(disclaimer_box)

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
